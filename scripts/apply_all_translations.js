// Now function to safely append missing keys to a file
function updateLanguageFile(langCode, dict) {
  const filePath = path.join('./src/i18n', `${langCode}.ts`);
  let content = fs.readFileSync(filePath, 'utf8');

  // Find where the object ends (before the closing '};')
  const lastBraceIdx = content.lastIndexOf('};');
  if (lastBraceIdx === -1) {
    console.error(`Could not find closing brace in ${filePath}`);
    return;
  }

  // Find which keys are not already in content
  const addedLines = [];
  for (const [k, v] of Object.entries(dict)) {
    // Check if key is already present
    const regex = new RegExp(`['"]${k.replace(/\./g, '\\.')}['"]\\s*:`);
    if (!regex.test(content)) {
      // Escape single quotes in value
      const safeVal = v.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
      addedLines.push(`  '${k}': '${safeVal}',`);
    }
  }

  if (addedLines.length > 0) {
    const before = content.slice(0, lastBraceIdx).trimEnd();
    const after = content.slice(lastBraceIdx);
    const updatedContent = `${before}\n\n  // Multilingual synchronization updates\n${addedLines.join('\n')}\n${after}`;
    fs.writeFileSync(filePath, updatedContent, 'utf8');
    console.log(`Updated ${langCode}.ts with ${addedLines.length} new keys.`);
  } else {
    console.log(`${langCode}.ts already has all keys!`);
  }
}

